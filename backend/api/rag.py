class TfidfIndex:
    def __init__(self):
        self.tf = defaultdict(lambda: defaultdict(float))
        self.idf = {}
        self.documents = {}
        self._build()

    def _tokenize(self, text: str) -> List[str]:
        text = re.sub(r'[^\w\s_]', ' ', text)
        text = text.replace('_', ' ')
        tokens = [t for t in text.lower().split() if len(t) > 0]
        text_no_space = re.sub(r'\s+', '', text)
        for i in range(len(text_no_space) - 1):
            bigram = text_no_space[i:i+2]
            if bigram not in tokens:
                tokens.append(bigram)
        for i in range(len(text_no_space) - 2):
            trigram = text_no_space[i:i+3]
            if trigram not in tokens:
                tokens.append(trigram)
        return tokens

    def _build(self):
        for doc_id, content in COMPLETE_KNOWLEDGE_BASE.items():
            text = ' '.join([
                content.get('disease_name', ''),
                content.get('diagnosis_summary', ''),
                ' '.join(content.get('symptoms', [])),
                ' '.join(content.get('causes', [])),
                ' '.join(content.get('immediate_measures', []))
            ])
            self.documents[doc_id] = text
            tokens = self._tokenize(text)
            token_counts = defaultdict(int)
            for token in tokens:
                token_counts[token] += 1
            for token, count in token_counts.items():
                self.tf[token][doc_id] = count / len(tokens)
        for token in self.tf:
            doc_freq = len(self.tf[token])
            self.idf[token] = math.log((len(COMPLETE_KNOWLEDGE_BASE) + 1) / (doc_freq + 0.5)) + 1

    def score(self, query: str, doc_id: str) -> float:
        query_tokens = self._tokenize(query)
        if not query_tokens:
            return 0.0
        score = 0.0
        for token in query_tokens:
            if token not in self.tf:
                continue
            tf = self.tf[token].get(doc_id, 0)
            idf = self.idf.get(token, 0)
            score += tf * idf
        return score


