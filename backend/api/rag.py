class IntentClassifier:
    def __init__(self):
        self.intent_patterns = {
            'disease_query': [r'.*病.*', r'.*病害.*', r'.*症状.*', r'.*病症.*'],
            'treatment_query': [r'.*用什么药.*', r'.*治疗.*', r'.*防治.*', r'.*药剂.*', r'.*施药.*'],
            'prevention_query': [r'.*预防.*', r'.*防止.*', r'.*避免.*', r'.*防控.*'],
            'comparison_query': [r'.*和.*区别.*', r'.*与.*对比.*', r'.*差异.*', r'.*不同.*'],
            'severity_query': [r'.*严重程度.*', r'.*轻重.*', r'.*程度.*', r'.*等级.*'],
            'cause_query': [r'.*原因.*', r'.*成因.*', r'.*为什么.*', r'.*诱因.*'],
            'symptom_description': [r'.*叶子.*', r'.*叶片.*', r'.*果实.*', r'.*枝条.*'],
            'emergency_query': [r'.*紧急.*', r'.*快速.*', r'.*立刻.*', r'.*马上.*'],
            'long_term_query': [r'.*长期.*', r'.*持续.*', r'.*根治.*', r'.*彻底.*'],
            'safety_query': [r'.*安全.*', r'.*间隔期.*', r'.*残留.*', r'.*毒性.*'],
            'diagnosis_request': [r'.*诊断.*', r'.*识别.*', r'.*判断.*', r'.*是什么病.*'],
            'cultural_practice': [r'.*修剪.*', r'.*施肥.*', r'.*浇水.*', r'.*管理.*'],
        }

    def classify(self, query: str) -> str:
        query_lower = query.lower()
        matched_intents = []
        for intent, patterns in self.intent_patterns.items():
            for pattern in patterns:
                if re.match(pattern, query_lower):
                    matched_intents.append(intent)
                    break
        if matched_intents:
            return matched_intents[0] if len(matched_intents) == 1 else 'complex_query'
        return 'general_query'


class QueryParser:
    def __init__(self):
        self.crops = ['苹果', '樱桃', '梨', '桃', '葡萄', '柑橘', '果树']
        self.diseases = ['黑星病', '黑斑病', '白粉病', '锈病', '炭疽病', '褐斑病',
                         '灰斑病', '花叶病', '腐烂病', '链格孢枯萎病', '雪松锈病']
        self.severity_levels = ['严重', '轻度', '一般', '中等', '轻微', '重度', '危急']
        self.query_types = ['症状', '治疗', '预防', '原因', '区别', '诊断']

    def extract_entities(self, query: str) -> Dict:
        entities = {
            'crops': [],
            'diseases': [],
            'severity': [],
            'query_types': [],
            'location': [],
            'time': []
        }
        for crop in self.crops:
            if crop in query:
                entities['crops'].append(crop)
        for disease in self.diseases:
            if disease in query:
                entities['diseases'].append(disease)
        for level in self.severity_levels:
            if level in query:
                entities['severity'].append(level)
        for qt in self.query_types:
            if qt in query:
                entities['query_types'].append(qt)
        location_patterns = [r'南方', r'北方', r'多雨', r'干燥', r'山区', r'平原']
        for pattern in location_patterns:
            if pattern in query:
                entities['location'].append(pattern)
        time_patterns = [r'春季', r'夏季', r'秋季', r'冬季', r'雨季', r'旱季']
        for pattern in time_patterns:
            if pattern in query:
                entities['time'].append(pattern)
        return entities

    def parse_comparison(self, query: str) -> Tuple[str, str]:
        separators = ['和', '与', '跟', '对比', '区别']
        for sep in separators:
            if sep in query:
                parts = query.split(sep)
                if len(parts) >= 2:
                    part1 = parts[0].strip()
                    part2 = sep.join(parts[1:]).replace('的区别', '').replace('区别', '').strip()
                    return (part1, part2)
        return (query, '')




